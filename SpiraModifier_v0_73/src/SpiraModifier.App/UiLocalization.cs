    private static readonly (string French, string English)[] OrderedPhraseTranslations =
        PhraseTranslations.OrderByDescending(pair => pair.French.Length).ToArray();

    public static string CurrentLanguage { get; private set; } = French;

    public static bool IsEnglish => CurrentLanguage == English;

    public static void SetLanguage(string? language)
    {
        CurrentLanguage = language == English ? English : French;
    }

    public static string Translate(string? text)
    {
        if (string.IsNullOrEmpty(text) || !IsEnglish)
            return text ?? string.Empty;

        var first = 0;
        while (first < text.Length && char.IsWhiteSpace(text[first])) first++;
        var last = text.Length - 1;
        while (last >= first && char.IsWhiteSpace(text[last])) last--;

        var prefix = text[..first];
        var core = last >= first ? text[first..(last + 1)] : string.Empty;
        var suffix = last + 1 < text.Length ? text[(last + 1)..] : string.Empty;

        if (ExactTranslations.TryGetValue(core, out var exact))
            return prefix + exact + suffix;

        var translated = core;
        foreach (var (french, english) in OrderedPhraseTranslations)
            translated = translated.Replace(french, english, StringComparison.Ordinal);

        return prefix + translated + suffix;
    }

    private static string TranslateBoundText(string text)
    {
        if (BoundTextTranslations.TryGetValue(text, out var exact))
            return exact;

        var translated = text;
        foreach (var (french, english) in BoundPhraseTranslations)
            translated = translated.Replace(french, english, StringComparison.Ordinal);
        return translated;
    }

    public static void Apply(DependencyObject root)
    {
        var visited = new HashSet<DependencyObject>(ReferenceEqualityComparer.Instance);
        ApplyRecursive(root, visited);
    }

    public static void ApplyReadOnlyTextBox(TextBox textBox)
    {
        TranslateProperty(textBox, TextBox.TextProperty);
    }

    public static void SetLocalizedReadOnlyTextBox(TextBox textBox, string source)
    {
        var properties = States.GetOrCreateValue(textBox);
        var localized = IsEnglish ? Translate(source) : source;
        properties[TextBox.TextProperty] = new PropertyState
        {
            Source = source,
            Displayed = localized,
        };
        textBox.SetCurrentValue(TextBox.TextProperty, localized);
    }

    private static IReadOnlyDictionary<string, string> BuildTranslations()
    {
        var result = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var (french, english) in TranslationEntries)
            result[french] = english;
        return result;
    }

    private static void ApplyRecursive(DependencyObject current, ISet<DependencyObject> visited)
    {
        if (!visited.Add(current)) return;

        TranslateProperty(current, ToolTipService.ToolTipProperty);

        switch (current)
        {
            case Window:
                TranslateProperty(current, Window.TitleProperty);
                break;
            case HeaderedContentControl:
                TranslateProperty(current, HeaderedContentControl.HeaderProperty);
                break;
            case HeaderedItemsControl:
                TranslateProperty(current, HeaderedItemsControl.HeaderProperty);
                break;
        }

        if (current is ContentControl)
            TranslateProperty(current, ContentControl.ContentProperty);
        if (current is TextBlock textBlock)
        {
            TranslateProperty(current, TextBlock.TextProperty);
            foreach (var inline in textBlock.Inlines.OfType<Inline>().ToList())
                ApplyInline(inline, visited);
        }
        if (current is Run)
            TranslateProperty(current, Run.TextProperty);
        if (current is DataGrid dataGrid)
        {
            foreach (var column in dataGrid.Columns)
                TranslateProperty(column, DataGridColumn.HeaderProperty);
        }

        if (current is TextBoxBase)
            return;

        foreach (var child in LogicalTreeHelper.GetChildren(current).OfType<DependencyObject>())
            ApplyRecursive(child, visited);

        if (current is Visual || current is Visual3D)
        {
            for (var index = 0; index < VisualTreeHelper.GetChildrenCount(current); index++)
                ApplyRecursive(VisualTreeHelper.GetChild(current, index), visited);
        }
    }

    private static void ApplyInline(Inline inline, ISet<DependencyObject> visited)
    {
        ApplyRecursive(inline, visited);
        if (inline is Span span)
        {
            foreach (var child in span.Inlines.OfType<Inline>().ToList())
                ApplyInline(child, visited);
        }
    }

    private static void TranslateProperty(DependencyObject target, DependencyProperty property)
    {
        if (target.GetValue(property) is not string current)
            return;

        var properties = States.GetOrCreateValue(target);
        if (!properties.TryGetValue(property, out var state) || current != state.Displayed)
        {
            state = new PropertyState { Source = current, Displayed = current };
            properties[property] = state;
        }

        var localized = IsEnglish
            ? BindingOperations.IsDataBound(target, property)
                ? TranslateBoundText(state.Source)
                : Translate(state.Source)
            : state.Source;
        if (current != localized)
            target.SetCurrentValue(property, localized);
        state.Displayed = localized;
    }
